<?php

declare(strict_types=1);

namespace App\Enums;

/**
 * Исход обработки события вебхука.
 *
 * Строковые значения совпадают с колонкой `webhook_events.outcome`
 * (VARCHAR(16)) и исходами FR-ORD-08 ТЗ plan/TZ-markethub-orders-service-v1.4.md:
 *
 * - `applied` — снимок применён;
 * - `stale` — версия снимка не новее сохранённой (FR-ORD-02);
 * - `ignored` — неизвестный тип или неизвестный строковый статус (FR-WH-07);
 * - `rejected` — свежий снимок отклонён из терминального статуса (FR-ORD-09).
 *
 * `duplicate` намеренно НЕ входит в enum: по FR-ORD-01/FR-ORD-08 это только
 * HTTP-ответ повторной доставке, исходный `outcome` события при дубле
 * не заменяется. Невалидные JSON/конверт/снимок (4xx) в журнал не пишутся.
 *
 * Словарь HTTP-ответа шире журнала (FR-WH-10): `applied` отдаётся наружу
 * как `processed`, плюс есть `duplicate`; маппинг — задача T-010.
 */
enum EventOutcome: string
{
    /** Снимок применён: заказ, история и (возможно) уведомления обновлены. */
    case APPLIED = 'applied';

    /** Версия снимка не новее сохранённой — состояние не менялось. */
    case STALE = 'stale';

    /** Неизвестный тип события или неизвестный статус — событие только сохранено. */
    case IGNORED = 'ignored';

    /** Свежий снимок отклонён из терминального статуса (Q35). */
    case REJECTED = 'rejected';
}
